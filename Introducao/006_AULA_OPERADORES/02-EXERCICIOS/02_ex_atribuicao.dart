// Demonstrar os operadores de atribuição do dart

void main() {
  int x = 10;

  // Operador de atribuição composto de adição
  x += 3;
  print('X += 3: $x');

  // Operador de atribuição composto de subtração
  x -= 2;
  print('X -= 2: $x');

  // Operador de atribuição composto de multiplicação
  x *= 4;
  print('X *= 4: $x');

  // Operador de atribuição composto de multiplicação
  x ~/= 3;
  print('X ~/= 3: $x');
}